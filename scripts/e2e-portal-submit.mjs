/**
 * e2e-portal-submit.mjs — end-to-end test driver against the live relay.
 *
 * Generates a fresh Ed25519 keypair, signs a sample descriptor, and
 * POSTs to relay.futurechain.eu/v1/portals/submit with a KYC blob.
 * Mirrors what ANTON Local's finalizeSession() will do once
 * RELAY_PORTAL_SUBMIT_URL is wired into production env. Standalone
 * so I can run it from the dev box without standing up the full
 * ANTON Local server first.
 *
 * Usage:
 *   node scripts/e2e-portal-submit.mjs [portal-name]
 */

import { generateKeyPairSync, createHash, sign } from 'node:crypto';
import { canonify } from '@truestamp/canonify';

const RELAY_BASE = process.env.RELAY_BASE ?? 'https://relay.futurechain.eu/v1';
const PORTAL_NAME = process.argv[2] ?? `e2e-test-${Date.now().toString(36)}`;

function bytesToHex(buf) {
  return Buffer.from(buf).toString('hex');
}
function b64url(buf) {
  return Buffer.from(buf).toString('base64')
    .replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}
function spkiHexToRawHex(spkiHex) {
  if (spkiHex.length !== 88) throw new Error(`expected 88-char SPKI hex, got ${spkiHex.length}`);
  return spkiHex.slice(24);  // strip 12-byte Ed25519 SPKI prefix
}
function deriveRelayContactHash(rawHex) {
  const CHARSET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  const hash = createHash('sha256').update(Buffer.from(rawHex, 'hex')).digest();
  const segs = [];
  for (let s = 0; s < 4; s++) {
    let seg = '';
    for (let c = 0; c < 4; c++) seg += CHARSET[hash[s * 4 + c] % CHARSET.length];
    segs.push(seg);
  }
  return `ANTON-${segs.join('-')}`;
}

async function main() {
  const { publicKey, privateKey } = generateKeyPairSync('ed25519');
  const spkiHex = bytesToHex(publicKey.export({ type: 'spki', format: 'der' }));
  const pemPriv = privateKey.export({ type: 'pkcs8', format: 'pem' });
  const rawHex = spkiHexToRawHex(spkiHex);
  const contactHash = deriveRelayContactHash(rawHex);

  // Canonical descriptor shape — nested under `portal` to match
  // ANTON Local's capability-descriptor builder + Comm App's PortalDescriptor
  // type. The relay accepts any signed blob; the Comm App reads
  // `descriptor.portal.displayTitle` so the test data must match.
  const now = new Date().toISOString();
  const oneYear = new Date(Date.now() + 365 * 24 * 3600 * 1000).toISOString();
  const descriptor = {
    schemaVersion: 'capability-1.0.0',
    descriptorId: `desc-${PORTAL_NAME}-${Date.now()}`,
    issuedAt: now,
    validFrom: now,
    validUntil: oneYear,
    portal: {
      name: `${PORTAL_NAME}.global.portal`,
      namespace: 'global',
      displayTitle: 'E2E test portal',
      category: 'personal',
      contactHash,
      publicKey: rawHex,
    },
    identity: {
      humanContact: { available: true, displayName: 'Daniel (E2E)' },
    },
    capabilities: [
      { id: 'cap-contact', verb: 'contact', title: 'Say hello',
        description: 'Drop me a line', tags: ['demo','test'] },
      { id: 'cap-inquire', verb: 'inquire', title: 'Ask a question',
        description: 'Stub capability for the e2e test', tags: ['demo'] },
    ],
    description: 'Generated by scripts/e2e-portal-submit.mjs for the friends-test loop.',
    tags: ['e2e','demo'],
    serviceAreas: ['SE'],
    languages: ['en'],
  };

  const canonical = canonify(descriptor);
  const sigBuf = sign(null, Buffer.from(canonical), pemPriv);
  const signature = b64url(sigBuf);

  const body = {
    proposedName: PORTAL_NAME,
    proposedNamespace: 'global',
    signingPubkeyHex: rawHex,
    submitterContactHash: contactHash,
    descriptorJson: descriptor,
    descriptorSignature: signature,
    kyc: {
      legalName: 'Daniel Bardun (E2E test)',
      idDocumentType: 'national_id',
      idDocumentNumber: `TEST-${PORTAL_NAME}`,
      idDocumentCountry: 'SE',
      contactEmail: 'daniel.bardun@gmail.com',
      addressCountry: 'SE',
      addressCity: 'Stockholm',
      addressStreet: 'Test address 1',
    },
  };

  console.log('── Submitting ──');
  console.log('  relay     :', RELAY_BASE);
  console.log('  portal    :', `${PORTAL_NAME}.global`);
  console.log('  contact   :', contactHash);
  console.log('  pubkey    :', rawHex.slice(0, 16) + '…');

  const res = await fetch(`${RELAY_BASE}/portals/submit`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify(body),
  });
  const out = await res.json();
  console.log('── Response ──');
  console.log('  status    :', res.status);
  console.log('  body      :', JSON.stringify(out, null, 2));
  if (!res.ok) process.exit(1);
}

main().catch((err) => { console.error('FAILED:', err); process.exit(1); });
